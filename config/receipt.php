<?php
declare(strict_types=1);

/**
 * 主动采集进程 payment:watch 的工程默认值；修改后重启 watch 生效。
 * 时长单位均为整数秒，数量单位见各项说明；请使用正整数，不以 0 表示关闭。
 * 平台登录态永久缓存，由插件依据平台响应判断失效；以下间隔和预算都不是缓存 TTL。
 * 此处不设置订单付款有效期、手机通知时间容差，也不覆盖通道表单中已保存的插件参数。
 */
return [
    // 每轮扫描、插件采集及可执行的预登录全部结束后，再等待 1 秒开始下一轮。
    // 缩短会增加数据库扫描频率；不表示每秒调用平台，更不保证一秒到账。
    'scan_interval_seconds' => 1,

    // 订单原付款截止后的补查期，300 秒即 5 分钟；用于核对延迟出现的原有效期内流水。
    // 超时/本地关闭订单在补查范围内仍可参与采集，但此值不延长付款窗口或接受过期付款。
    'late_check_seconds' => 300,

    // 每次从本地数据库分页读取最多 500 条候选支付单，收齐同插件候选后再交给插件。
    // 这是本地取数批量，不是平台流水分页；平台每账号单次取最新最多 200 条，不翻页。
    'order_page_size' => 500,

    // 单插件本轮最多装配 10000 条候选支付单，用于限制内存及匹配工作量。
    // 超限时该插件本轮明确报容量异常，不截取前 10000 条继续匹配；其他插件仍可处理。
    'max_orders_per_plugin' => 10000,

    // 一个账号本次处理的外部请求预算：登录、刷新状态、查询共用截止时间，不是每个请求各 15 秒。
    // 实际截止取“当前时间 + 15 秒”和本轮插件截止的较早者，单次 HTTP 仍受 SDK 自身超时限制。
    'account_budget_seconds' => 15,

    // 每个插件完成候选装配后，collect 与其后可执行的 prelogin 共用最多 30 秒外部请求预算。
    // 不是全部插件合计 30 秒，也不是 PHP 强制中断定时器；数据库装配、逐笔确认不由它终止。
    'plugin_budget_seconds' => 30,

    // 声明 prelogin=true 的采集插件，通常距上次成功验证 600 秒（10 分钟）后低频验证登录态。
    // 正常查单可更新验证时间；平台凭证临近失效、认证变化和失败退避仍由插件按实际情况处理。
    // 不表示每 600 秒重新登录或清空缓存；支付宝账单未声明预登录，不使用此探测间隔。
    'prelogin_interval_seconds' => 600,
];
